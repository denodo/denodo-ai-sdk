"""
DeepQuery report endpoints.

Reports are generated by background jobs (see services/report_jobs.py) and
persisted in the chatbot database. These endpoints let the UI poll the status,
cancel running jobs, create language variants and read or delete reports.
Every endpoint is scoped to the logged-in user.
"""

import json
import logging

from flask import Blueprint, request, jsonify
from flask_login import login_required, current_user

from utils.database_utils import DeepQueryReports
from sample_chatbot.config import get_config
from sample_chatbot.services.report_jobs import (
    ReportJobContext,
    ReportNotFoundError,
    ReportLimitError,
    ReportQueueFullError,
    VariantUnavailableError,
    get_max_reports_per_user,
    report_job_manager,
)

logger = logging.getLogger(__name__)

reports_bp = Blueprint('reports', __name__)

_PRIVATE_FIELDS = ("user_id", "agent_id")

def _user():
    """Resolve the underlying user (not the LocalProxy)."""
    return current_user._get_current_object()

def _public_report(report):
    """Report info safe to send to the browser (no owner columns)."""
    return {key: value for key, value in report.items() if key not in _PRIVATE_FIELDS}

def _job_context(user):
    """Job context from the logged-in user's session (the password stays in memory only)."""
    config = get_config(user.agent_id)
    chatbot = user.get_or_create_chatbot()
    return ReportJobContext(
        user_id=user.id,
        password=user.password,
        agent_id=user.agent_id,
        api_host=config.ai_sdk_host,
        verify_ssl=config.ai_sdk_verify_ssl,
        timeout=config.chatbot_timeout,
        ai_sdk_params=dict(chatbot.ai_sdk_params or {}),
    )

def _not_found():
    return jsonify({"success": False, "error": "Report not found."}), 404

def _queue_full(error):
    return jsonify({"success": False, "error": str(error), "code": "queue_full"}), 503

def _limit_reached(error):
    return jsonify({"success": False, "error": str(error), "code": "report_limit", "limit": get_max_reports_per_user()}), 409

@reports_bp.route('/api/reports/status', methods=['GET'])
@login_required
def reports_status():
    """List all the user's reports (any agent) and the per-user report limit. Never returns HTML or metadata."""
    user = _user()
    reports = DeepQueryReports.list_reports(user.id)
    return jsonify({
        "reports": [_public_report(report) for report in reports],
        "limit": get_max_reports_per_user(),
    })

@reports_bp.route('/api/reports/<report_id>/html', methods=['GET'])
@login_required
def report_html(report_id):
    """Return the stored HTML of a completed report."""
    user = _user()
    report = DeepQueryReports.get_report_html(report_id, user.id)
    if report is None:
        return _not_found()
    if not report["html"]:
        return jsonify({"success": False, "error": "The report is not ready yet."}), 409
    return jsonify({"html_report": report["html"], "title": report["title"]})

@reports_bp.route('/api/reports/<report_id>/analysis', methods=['GET'])
@login_required
def report_analysis(report_id):
    """Return the question and stored deepquery_metadata (VQL, tables, graphs) behind a report."""
    user = _user()
    report = DeepQueryReports.get_report(report_id, user.id)
    if not report:
        return _not_found()

    analysis = DeepQueryReports.get_analysis(report["analysis_id"], user.id)
    if not analysis or not analysis.get("metadata"):
        return jsonify({"success": False, "error": "The analysis data is not available (yet)."}), 409
    return jsonify({
        "question": analysis["question"],
        "title": analysis.get("title") or report["title"],
        "deepquery_metadata": analysis["metadata"],
    })

@reports_bp.route('/api/reports/<report_id>/cancel', methods=['POST'])
@login_required
def cancel_report(report_id):
    """Cancel a pending or running report."""
    user = _user()
    try:
        cancelled = report_job_manager.cancel(report_id, user.id)
    except ReportNotFoundError:
        return _not_found()
    if not cancelled:
        return jsonify({"success": False, "error": "Only pending or running reports can be cancelled."}), 409
    return jsonify({"success": True})

@reports_bp.route('/api/reports/<report_id>/variant', methods=['POST'])
@login_required
def create_variant(report_id):
    """Generate the same analysis in another language, reusing the stored data."""
    user = _user()
    data = request.get_json(silent=True) or {}
    language = (data.get('language') or '').strip()
    if not language:
        return jsonify({"success": False, "error": "Missing language."}), 400

    ctx = _job_context(user)

    try:
        report = report_job_manager.variant(ctx, report_id, language)
    except ReportNotFoundError:
        return _not_found()
    except VariantUnavailableError as e:
        return jsonify({"success": False, "error": str(e)}), 409
    except ReportLimitError as e:
        return _limit_reached(e)
    except ReportQueueFullError as e:
        return _queue_full(e)
    except ValueError as e:
        return jsonify({"success": False, "error": str(e)}), 400

    return jsonify({"success": True, "report": _public_report(report)}), 201

@reports_bp.route('/api/reports', methods=['POST'])
@login_required
def create_reports():
    """Queue a new DeepQuery analysis (one report per language) from its question."""
    user = _user()
    data = request.get_json(silent=True) or {}
    question = str(data.get('question') or '').strip()[:4000]
    if not question:
        return jsonify({"success": False, "error": "Missing question."}), 400
    if not user.password:
        return jsonify({"success": False, "error": "Your session cannot be used to generate the report. Please log in again."}), 409

    try:
        _, reports = report_job_manager.submit(_job_context(user), question, data.get('languages'))
    except ReportLimitError as e:
        return _limit_reached(e)
    except ReportQueueFullError as e:
        return _queue_full(e)
    except ValueError as e:
        return jsonify({"success": False, "error": str(e)}), 400
    created = [DeepQueryReports.get_report(report['report_id'], user.id) for report in reports]
    return jsonify({"success": True, "reports": [_public_report(report) for report in created if report]}), 201

@reports_bp.route('/api/reports/<report_id>/retry', methods=['POST'])
@login_required
def retry_report(report_id):
    """Re-run a failed or cancelled report in place."""
    user = _user()
    if not user.password:
        return jsonify({"success": False, "error": "Your session cannot be used to retry this report. Please log in again."}), 409
    try:
        report = report_job_manager.retry(_job_context(user), report_id)
    except ReportNotFoundError:
        return _not_found()
    except ReportQueueFullError as e:
        return _queue_full(e)
    except (VariantUnavailableError, ValueError) as e:
        return jsonify({"success": False, "error": str(e)}), 409
    return jsonify({"success": True, "report": _public_report(report)})

_MAX_LEGACY_METADATA_BYTES = 30 * 1024 * 1024

@reports_bp.route('/api/reports/from-legacy', methods=['POST'])
@login_required
def report_from_legacy():
    """Create a report from the deepquery_metadata of a chat message generated before async reports."""
    user = _user()
    data = request.get_json(silent=True) or {}
    metadata = data.get('deepquery_metadata')
    question = str(data.get('question') or '')[:4000]
    language = (data.get('language') or '').strip()

    if not isinstance(metadata, dict) or not metadata:
        return jsonify({"success": False, "error": "Missing deepquery_metadata."}), 400
    if len(json.dumps(metadata, default=str)) > _MAX_LEGACY_METADATA_BYTES:
        return jsonify({"success": False, "error": "deepquery_metadata is too large."}), 413
    if not user.password:
        return jsonify({"success": False, "error": "Your session cannot be used to generate the report. Please log in again."}), 409

    try:
        report = report_job_manager.submit_from_legacy(_job_context(user), question, metadata, language)
    except ReportLimitError as e:
        return _limit_reached(e)
    except ReportQueueFullError as e:
        return _queue_full(e)
    except ValueError as e:
        return jsonify({"success": False, "error": str(e)}), 400
    return jsonify({"success": True, "report": _public_report(report)}), 201

@reports_bp.route('/api/reports/<report_id>', methods=['DELETE'])
@login_required
def delete_report(report_id):
    """Delete a report (cancelling it first if it is still running)."""
    user = _user()
    if not report_job_manager.delete(report_id, user.id):
        return _not_found()
    return jsonify({"success": True})

@reports_bp.route('/api/reports', methods=['DELETE'])
@login_required
def delete_all_reports():
    """Delete every report of the user."""
    user = _user()
    deleted = report_job_manager.delete_all(user.id)
    return jsonify({"success": True, "deleted": deleted})
